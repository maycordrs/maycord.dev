<section aria-labelledby="overview">
  <h2 id="overview">what maycord is</h2>
  <p>
    maycord is an upcoming mod for discord’s native rust app. a mod changes an installed official client rather
    than replacing it with an independent app. maycord’s goal is to add themes, plugins, and other ways to make
    that client feel more like your own.
  </p>
</section>

<section id="how" aria-labelledby="fpui">
  <h2 id="fpui">built on fpui</h2>
  <p>
    fpui is the runtime mod framework underneath maycord, built for native gpui apps. we split the reusable
    patching engine into its own project so it could be used beyond discord, while maycord could focus on its
    client integration.
  </p>
</section>

